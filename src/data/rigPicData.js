/**
 * Cari driver/PIC berdasarkan nama rig kendaraan.
 * Mendukung berbagai format: "BMS 02", "BMS02", "02", dll.
 * @returns {object|null} Driver object pertama di rig, atau null jika tidak ditemukan
 */
export function getPicByRig(rig) {
  if (!rig) return null;

  const rigNorm = String(rig).trim().toUpperCase().replace(/\s+/g, " ");

  for (const [key, drivers] of Object.entries(RIG_DRIVERS)) {
    const keyNorm = key.toUpperCase().replace(/\s+/g, " ");

    if (
      rigNorm === keyNorm ||
      rigNorm === keyNorm.replace("BMS ", "BMS") ||
      ("BMS " + rigNorm) === keyNorm ||
      rigNorm.replace("BMS ", "") === keyNorm.replace("BMS ", "")
    ) {
      return drivers[0] ? { ...drivers[0], allDrivers: drivers } : null;
    }
  }

  return null;
}

